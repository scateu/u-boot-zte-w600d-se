#!/usr/bin/env python3
"""Write sig.h: two 64-byte pixel windows of the logo that is on screen (p17, U-Boot BMP copy).
demo.c searches RAM for SIG1 and confirms with SIG2 to find the logo framebuffer.

usage: mksig.py <logo.img (flashed p17 image)> <sig.h>
"""
import sys

W, H, ROW, HDR, LEN = 1920, 1080, 1920 * 3, 54, 64


def best_window(px, y1, y2):
    """x (pixels) of the 64-byte window most varied in both rows y1, y2 (rows are stored top-down)"""
    r1, r2 = px[y1 * ROW:(y1 + 1) * ROW], px[y2 * ROW:(y2 + 1) * ROW]
    return max(range(0, W - LEN // 3),
               key=lambda x: min(len(set(r1[x * 3:x * 3 + LEN])), len(set(r2[x * 3:x * 3 + LEN]))))


def main():
    img = open(sys.argv[1], 'rb').read()
    assert img[:2] == b'BM'
    px = img[HDR:HDR + ROW * H]
    # the logo is near-black (01 01 02) except the China Mobile emblem (rows ~400..680) and the
    # "W600D LINUX" text: use the two most colourful rows, at least 40 rows apart
    colours = lambda y: len(set(px[y * ROW + i:y * ROW + i + 3] for i in range(0, ROW, 3)))
    rank = sorted(range(H), key=colours, reverse=True)
    y1 = rank[0]
    y2 = next(y for y in rank if abs(y - y1) >= 40)
    x = best_window(px, y1, y2)
    s1 = px[y1 * ROW + x * 3:y1 * ROW + x * 3 + LEN]
    s2 = px[y2 * ROW + x * 3:y2 * ROW + x * 3 + LEN]
    assert len(set(s1)) > 2 and len(set(s2)) > 2 and s1 != s2, 'signature rows not distinctive'
    assert px.count(s1) == 1, 'SIG1 not unique in the logo'
    with open(sys.argv[2], 'w') as f:
        f.write('/* generated by mksig.py from %s */\n' % sys.argv[1].split('/')[-1])
        f.write('#define SIG_X %d  /* byte offset in the row (pixel x=%d) */\n' % (x * 3, x))
        f.write('#define SIG1_Y %d\n#define SIG2_Y %d\n#define SIG_LEN %d\n' % (y1, y2, LEN))
        for n, s in (('SIG1', s1), ('SIG2', s2)):
            f.write('static const unsigned char %s[%d] = {%s};\n' % (n, LEN, ','.join(str(b) for b in s)))
    print('SIG at x=%d, rows %d/%d' % (x, y1, y2))


if __name__ == '__main__':
    main()
